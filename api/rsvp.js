// RSVP replies for the invitation, stored in the Redis database connected to this Vercel project
// (Vercel dashboard > Storage > Upstash for Redis > Connect Project).
//   POST /api/rsvp  code=<invitation code>&response=Attending|Not attending   (from a guest's invitation)
//   GET  /api/rsvp  -> { code: { response, at } }                             (for the guest list page)
const GUESTS = require("./_guests.js"); // generated by guest-list/make_guest_links.py

const ANSWERS = ["Attending", "Not attending"];
// Vercel may add a custom prefix to these names (e.g. STORAGE_KV_REST_API_URL), so match on the ending.
const env = suffix => Object.keys(process.env).filter(k => k.endsWith(suffix) && !k.includes("READ_ONLY")).map(k => process.env[k])[0];
const DB_URL = env("KV_REST_API_URL") || env("REDIS_REST_URL");
const DB_TOKEN = env("KV_REST_API_TOKEN") || env("REDIS_REST_TOKEN");

async function redis(command) {
  const r = await fetch(DB_URL, {
    method: "POST",
    headers: { Authorization: `Bearer ${DB_TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify(command),
  });
  const out = await r.json();
  if (!r.ok || out.error) throw new Error(out.error || `Database error ${r.status}`);
  return out.result;
}

function body(req) {
  if (req.body && typeof req.body === "object") return req.body;
  return Object.fromEntries(new URLSearchParams(String(req.body || "")));
}

module.exports = async (req, res) => {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Cache-Control", "no-store");
  if (req.method === "OPTIONS") return res.status(204).end();
  if (!DB_URL || !DB_TOKEN) return res.status(503).json({ ok: false, error: "RSVP storage is not connected yet" });

  try {
    if (req.method === "GET") {
      const flat = (await redis(["HGETALL", "rsvp"])) || [];
      const out = {};
      for (let i = 0; i < flat.length; i += 2) {
        try { out[flat[i]] = JSON.parse(flat[i + 1]); } catch {}
      }
      return res.status(200).json(out);
    }
    if (req.method === "POST") {
      const p = body(req);
      const code = String(p.code || "").trim().toLowerCase();
      const response = ANSWERS.includes(p.response) ? p.response : "";
      if (!GUESTS[code]) return res.status(404).json({ ok: false, error: "Unknown invitation" });
      if (!response) return res.status(400).json({ ok: false, error: "Invalid reply" });
      await redis(["HSET", "rsvp", code, JSON.stringify({ response, at: new Date().toISOString() })]);
      return res.status(200).json({ ok: true, response });
    }
    res.setHeader("Allow", "GET, POST");
    return res.status(405).json({ ok: false, error: "Method not allowed" });
  } catch (e) {
    return res.status(500).json({ ok: false, error: "Could not save the reply" });
  }
};
