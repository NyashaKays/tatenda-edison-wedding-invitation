// Shared helpers for the API functions (files starting with "_" are not routes on Vercel).
const crypto = require("crypto");
const BASE = require("./_guests.js"); // the original guest list, generated by guest-list/make_guest_links.py

// Vercel may add a custom prefix to these names (e.g. STORAGE_KV_REST_API_URL), so match on the ending.
const env = suffix => Object.keys(process.env).filter(k => k.endsWith(suffix) && !k.includes("READ_ONLY")).map(k => process.env[k])[0];
const DB_URL = env("KV_REST_API_URL") || env("REDIS_REST_URL");
const DB_TOKEN = env("KV_REST_API_TOKEN") || env("REDIS_REST_TOKEN");

async function redis(command) {
  const r = await fetch(DB_URL, {
    method: "POST",
    headers: { Authorization: `Bearer ${DB_TOKEN}`, "Content-Type": "application/json" },
    body: JSON.stringify(command),
  });
  const out = await r.json();
  if (!r.ok || out.error) throw new Error(out.error || `Database error ${r.status}`);
  return out.result;
}

const parse = s => { try { return JSON.parse(s); } catch { return null; } };

async function hashAll(key) {
  const flat = (await redis(["HGETALL", key])) || [];
  const out = {};
  for (let i = 0; i < flat.length; i += 2) { const v = parse(flat[i + 1]); if (v) out[flat[i]] = v; }
  return out;
}

// The bride's changes are stored in the "guests" hash: code -> {name, entry} or {removed: true}.
async function getGuest(code) {
  const edit = parse(await redis(["HGET", "guests", code]));
  if (edit) return edit.removed ? { removed: true } : edit;
  return BASE[code] || null;
}

function body(req) {
  if (req.body && typeof req.body === "object") return req.body;
  const raw = String(req.body || "");
  return parse(raw) || Object.fromEntries(new URLSearchParams(raw));
}

function cors(res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, X-Admin-Passcode");
  res.setHeader("Cache-Control", "no-store");
}

// Edits need the passcode set as ADMIN_PASSCODE in the Vercel project's environment variables.
function isAdmin(req) {
  const want = process.env.ADMIN_PASSCODE || "";
  const got = String(req.headers["x-admin-passcode"] || "");
  if (!want) return false;
  const h = s => crypto.createHash("sha256").update(s).digest();
  return crypto.timingSafeEqual(h(want), h(got));
}

module.exports = { BASE, ready: !!(DB_URL && DB_TOKEN), redis, hashAll, getGuest, body, cors, isAdmin };
